/* ============================================================
 * pages/live.js — 直播流录制（#/live）→ 重定向桩
 * ------------------------------------------------------------
 * 2026-11-07 起，「直播流录制」只有**一个页面**：#/launch/live
 * （pages/launcher.js 的 live 子视图，启动器双击直接落地的那一屏）。
 *
 * 原来这里有一个几乎一模一样的控制台副本（pages/live.js，#/live），
 * 两者功能重叠、各自还带一个「桌面窗口（高级）」入口 —— 是全站最明显
 * 的重复。桌面窗口退役时（其设置对话框 / 导出日志 / 复制原始输入等
 * 全部功能已并入 launcher.js 的 live 视图），这份副本一并退役：
 * 旧链接、旧书签在这里被送回唯一的页面，不留死路。
 *
 * 桌面 PyQt 窗口（modules/live_recorder/main.py）随之不再是功能入口；
 * 它保留在模块里仅作为离线排障的最后手段，不再从界面 reachable。
 * ============================================================ */
(function () {
  'use strict';

  window.DYRouter.register('live', function render() {
    /* 立即跳到唯一的直播流录制页面。用 router 的 go() 走正规切换
     * （hash 会变成 #/launch/live），浏览器历史里留的是干净的一跳。 */
    window.DYRouter.go('launch/live');
  });
})();
