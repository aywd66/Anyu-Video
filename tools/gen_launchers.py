# -*- coding: utf-8 -*-
"""生成统一的启动器：根目录唯一的 启动工具箱.bat。

2026-11-07 第一版：菜单式。第二版：双击直达主界面 + 自动启动手机下载。
2026-11-08 第三版（当前）：**手机下载服务删除** —— 双击只做一件事：
    启动工具箱主界面窗口（launcher_win.py toolbox，内部自动拉起桥接
    服务 127.0.0.1:8518 —— 全部模块统一在这里管理）。脚本随即退出，
    控制台自动关闭（bat 固有的短暂黑框无法消除，一闪而过属正常）。
    高级用法（参数模式）：
        启动工具箱.bat bridge     前台桥接调试（浏览器 127.0.0.1:8518）

硬约束（每一条都真踩过坑）：
  - .bat 必须 CRLF：LF 会让 goto / if 块 / set 错位
  - .bat 必须 GBK（cp936）：cmd.exe 用控制台代码页（中文 Windows 默认 936）
    逐行解析 .bat 字节。UTF-8 文件 + 文件中途 chcp 65001 实测会让
    字节-字符对齐错位，中文 echo 行被从多字节中间劈开、当成命令执行。
  - **chcp 铁律**：行首 chcp 只允许出现在文件尾部（bridge 前台模式的
    分支里），且**首个行首 chcp 之后到文件尾必须全为 ASCII**
    （代码页切到 65001 后，GBK 中文行会被解析错位；纯 ASCII 在任何
    代码页下解析结果一致）。生成器对这条做逐字节校验。
  - 历史版本曾有 .vbs 壳与手机下载（8520）——均已退役，勿复活。

跑法：
    python tools/gen_launchers.py            # 重新生成 启动工具箱.bat
    python tools/gen_launchers.py --check    # 只校验产物 == 生成器输出，不写盘
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

TARGET = os.path.join(ROOT, "启动工具箱.bat")

TPL = r"""@echo off
setlocal EnableExtensions
set "HERE=%~dp0"
cd /d "%HERE%"
title 视频下载工具箱

rem ============================================================
rem  Douzy unified launcher - the ONLY launcher in this dir.
rem  Generated by tools\gen_launchers.py - do not hand-edit.
rem
rem  Double-click (no args)  : open the toolbox main window
rem    (launcher_win.py toolbox) which auto-starts the bridge
rem    service on 127.0.0.1:8518 - the unified console for every
rem    module. The console closes by itself right after.
rem  启动工具箱.bat bridge    : foreground bridge debug console
rem
rem  ENCODING: this file is GBK (cp936), CRLF. Do NOT save it as
rem  UTF-8 and do NOT add a chcp before Chinese echo lines: a
rem  mid-file codepage switch desyncs cmd's parser (Chinese echo
rem  lines get split mid-multibyte and run as commands). The only
rem  chcp line lives in the tail branch (bridge), and everything
rem  after the first one is pure ASCII - the generator verifies
rem  that byte-by-byte.
rem ============================================================

rem ---------- locate python.exe / pythonw.exe ----------
set "PYW="
set "PY="
for %%V in (douyin-venv kuaishou-env live-recorder-env) do (
    if not defined PYW if exist "%HERE%runtime\%%V\Scripts\pythonw.exe" set "PYW=%HERE%runtime\%%V\Scripts\pythonw.exe"
    if not defined PY if exist "%HERE%runtime\%%V\Scripts\python.exe" set "PY=%HERE%runtime\%%V\Scripts\python.exe"
)
if not defined PYW for /f "delims=" %%P in ('where pythonw 2^>nul') do if not defined PYW set "PYW=%%~fP"
if not defined PY for /f "delims=" %%P in ('where python 2^>nul') do if not defined PY set "PY=%%~fP"

set "APP=%HERE%modules\douyin\webui\launcher_win.py"
set "BRIDGE=%HERE%modules\douyin\webui\bridge_server.py"

rem ---------- dispatch ----------
set "MODE=%~1"
if "%MODE%"=="" goto mode_gui
if /i "%MODE%"=="bridge" goto mode_bridge
echo [错误] 未知参数：%MODE%
echo         可用参数：bridge
echo         不带参数直接双击 = 打开工具箱主界面。
pause
exit /b 1

:mode_gui
if not defined PYW (
    echo [错误] 没有找到 Python 运行时，请检查 runtime 目录。
    pause
    exit /b 1
)
if not exist "%APP%" (
    echo [错误] 找不到启动器脚本 modules\douyin\webui\launcher_win.py
    pause
    exit /b 1
)
start "" "%PYW%" "%APP%" toolbox
exit /b 0

rem ============================================================
rem  Tail zone: from the first `chcp` line below to EOF the file
rem  must stay pure ASCII (generator verifies it). This foreground
rem  mode switches the console to UTF-8 so Python can print its
rem  Chinese banner without UnicodeEncodeError.
rem ============================================================

:mode_bridge
chcp 65001 >nul
set "PYTHONUTF8=1"
if not defined PY goto nopy
if not exist "%BRIDGE%" (
    echo [ERROR] Bridge script not found: modules\douyin\webui\bridge_server.py
    pause
    exit /b 1
)
title Douzy Bridge Debug - http://127.0.0.1:8518 - close to stop
"%PY%" "%BRIDGE%"
set "RC=%errorlevel%"
if not "%RC%"=="0" (
    echo.
    echo [ERROR] Bridge exited with code %RC%.
    pause
)
exit /b %RC%

:nopy
echo [ERROR] Python runtime not found. Check the runtime\ directory.
pause
exit /b 1
"""

MUST_CONTAIN = [
    "launcher_win.py", "bridge_server.py", ":mode_gui", ":mode_bridge",
]


def crlf(s):
    """统一成 CRLF —— 必须作用在**文本**上，不能作用在编码后的字节上。"""
    return s.replace("\r\n", "\n").replace("\r", "\n").replace("\n", "\r\n")


def build_bytes():
    """模板 -> 目标字节（GBK + CRLF），并做产物级自检。任何一条不过直接抛。"""
    text = crlf(TPL)
    lines = text.split("\r\n")

    # chcp 铁律：首个行首 chcp 之后到文件尾必须全为 ASCII。
    chcp_idx = [i for i, l in enumerate(lines) if l.lstrip().lower().startswith("chcp")]
    if chcp_idx:
        tail = "\r\n".join(lines[chcp_idx[0]:])
        if any(b > 0x7F for b in tail.encode("gbk")):
            raise AssertionError("首个行首 chcp 之后到文件尾存在非 ASCII 字节，"
                                 "代码页切换后中文会解析错位")

    raw = text.encode("gbk")             # GBK 断言：编码不了的字符在这里抛

    # GBK 尾字节不得撞上 0x7C('|') / 0x5E('^')：虽然合法 MBCS 解码不会把
    # 双字节对里的尾字节当特殊字符，但保险起见禁止这种组合出现。
    bad = []
    i = 0
    while i < len(raw):
        b = raw[i]
        if 0x81 <= b <= 0xFE and i + 1 < len(raw):
            t = raw[i + 1]
            if t in (0x7C, 0x5E) and 0x40 <= t <= 0xFE:
                bad.append((i, hex(b), hex(t)))
            i += 2
        else:
            i += 1
    if bad:
        raise AssertionError("GBK 尾字节撞特殊字符: %r" % bad[:10])

    # 产物字节必须能完整还原成模板文本（编码无信息丢失）
    if raw.decode("gbk") != text:
        raise AssertionError("GBK 编解码回环不一致")

    # 关键片段齐全（防模板被误删关键分支）
    for key in MUST_CONTAIN:
        if key not in text:
            raise AssertionError("模板缺少关键片段: %r" % key)

    # CRLF 断言
    if raw.count(b"\r\n") != raw.count(b"\n"):
        raise AssertionError("存在裸 LF")

    return raw


def main():
    raw = build_bytes()
    if "--check" in sys.argv[1:]:
        if not os.path.exists(TARGET):
            print("MISSING %s" % TARGET)
            return 1
        disk = open(TARGET, "rb").read()
        if disk == raw:
            print("OK 启动工具箱.bat 与生成器输出逐字节一致 (%d bytes)" % len(raw))
            return 0
        print("MISMATCH 启动工具箱.bat 与生成器输出不一致")
        print("  磁盘: %d bytes, 生成器: %d bytes" % (len(disk), len(raw)))
        return 1
    with open(TARGET, "wb") as f:
        f.write(raw)
    print("wrote 启动工具箱.bat %d bytes (GBK + CRLF, direct-GUI launcher)" % len(raw))
    return 0


if __name__ == "__main__":
    sys.exit(main())
